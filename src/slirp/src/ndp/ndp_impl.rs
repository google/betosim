use std::{collections::HashMap, net::Ipv6Addr};

use bytes::Bytes;
use netsim_packets::{
    EthernetFrame, IP_P_ICMPV6, Icmpv6Header, Icmpv6Type, Ipv6Builder, Ipv6Header, MacAddr,
    NDP_HOP_LIMIT, NeighborAdvertisementBuilder, NeighborSolicitation, RouterAdvertisementBuilder,
    ether_type, icmpv6_checksum, na_flags,
};
use serde::{Deserialize, Serialize};
use zerocopy::FromBytes;

use crate::Config;

/// Virtual SLiRP gateway link-local IPv6 address (matching C libslirp vhost_ll6).
pub(crate) const GATEWAY_LINK_LOCAL_IPV6: Ipv6Addr = Ipv6Addr::new(0xfe80, 0, 0, 0, 0, 0, 0, 2);

pub(crate) const ALL_NODES_MULTICAST_V6: Ipv6Addr = Ipv6Addr::new(0xff02, 0, 0, 0, 0, 0, 0, 1);
pub(crate) const ALL_NODES_MAC: MacAddr = MacAddr { bytes: [0x33, 0x33, 0x00, 0x00, 0x00, 0x01] };
pub(crate) const RA_CUR_HOP_LIMIT: u8 = 64;
pub(crate) const RA_ROUTER_LIFETIME_SECS: u16 = 1800;
pub(crate) const SLAAC_PREFIX_LEN: u8 = 64;
const IPV6_MIN_MTU: usize = 1280;

#[derive(Clone, Debug, Serialize, Deserialize)]
pub(crate) struct NdpEntry {
    mac: MacAddr,
    #[serde(skip)]
    last_accessed_tick: u64,
}

/// Handles Neighbor Discovery Protocol (NDP) for IPv6.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct NdpTable {
    pub(crate) cache: HashMap<Ipv6Addr, NdpEntry>,
    pub(crate) access_counter: u64,
}

impl Default for NdpTable {
    fn default() -> Self {
        Self::new()
    }
}

impl NdpTable {
    pub fn new() -> Self {
        Self { cache: HashMap::new(), access_counter: 0 }
    }

    /// Adds or updates an entry in the NDP table with bounded size limit and
    /// LRU eviction.
    pub fn add_entry(&mut self, ip: Ipv6Addr, mac: MacAddr) {
        const MAX_NDP_ENTRIES: usize = 512;
        self.access_counter = self.access_counter.wrapping_add(1);
        let current_tick = self.access_counter;

        crate::utils::lru::evict_lru(&mut self.cache, MAX_NDP_ENTRIES, &ip, |entry| {
            entry.last_accessed_tick
        });

        self.cache.insert(ip, NdpEntry { mac, last_accessed_tick: current_tick });
    }

    /// Looks up a MAC address for the given IPv6 address.
    pub fn lookup(&self, ip: &Ipv6Addr) -> Option<MacAddr> {
        self.cache.get(ip).map(|entry| entry.mac)
    }
}

/// Represents an NDP reply generated by the virtual router.
#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) enum NdpReply {
    NeighborAdvertisement {
        src_mac: MacAddr,
        dst_mac: MacAddr,
        src_ip: Ipv6Addr,
        dst_ip: Ipv6Addr,
        target_ip: Ipv6Addr,
        target_mac: MacAddr,
        flags: u8,
    },
    RouterAdvertisement {
        src_mac: MacAddr,
        dst_mac: MacAddr,
        src_ip: Ipv6Addr,
        dst_ip: Ipv6Addr,
        prefix: [u8; 16],
        prefix_len: u8,
        dns_server: Ipv6Addr,
    },
}

impl NdpReply {
    fn router_advertisement(config: &Config, dst_ip: Ipv6Addr, dst_mac: MacAddr) -> Self {
        let prefix = (u128::from(config.guest_ipv6)
            & (u128::MAX << (u128::BITS - u32::from(SLAAC_PREFIX_LEN))))
        .to_be_bytes();
        Self::RouterAdvertisement {
            src_mac: config.gateway_mac,
            dst_mac,
            src_ip: config.host_ipv6,
            dst_ip,
            prefix,
            prefix_len: SLAAC_PREFIX_LEN,
            dns_server: config.host_ipv6,
        }
    }

    /// Creates a periodic unsolicited Router Advertisement packet.
    pub(crate) fn periodic_router_advertisement(config: &Config) -> Self {
        Self::router_advertisement(config, ALL_NODES_MULTICAST_V6, ALL_NODES_MAC)
    }

    /// Encodes the NDP reply into the provided buffer as a complete Ethernet + IPv6 + ICMPv6 frame.
    ///
    /// Returns the number of bytes written, or `None` if the buffer is too small.
    pub(crate) fn encode(&self, buf: &mut [u8]) -> Option<usize> {
        match self {
            Self::NeighborAdvertisement {
                src_mac,
                dst_mac,
                src_ip,
                dst_ip,
                target_ip,
                target_mac,
                flags,
            } => {
                let hdr = Icmpv6FrameHeader {
                    src_mac: *src_mac,
                    dst_mac: *dst_mac,
                    src_ip: *src_ip,
                    dst_ip: *dst_ip,
                    icmp_type: Icmpv6Type::NeighborAdvertisement,
                };
                encode_icmpv6_frame(
                    buf,
                    &hdr,
                    |icmp_hdr| icmp_hdr.set_na_flags(*flags),
                    |payload| {
                        NeighborAdvertisementBuilder::new(payload)?
                            .target_addr(target_ip.octets())
                            .target_link_layer_addr(target_mac.bytes)
                            .build()
                    },
                )
            }
            Self::RouterAdvertisement {
                src_mac,
                dst_mac,
                src_ip,
                dst_ip,
                prefix,
                prefix_len,
                dns_server,
            } => {
                let hdr = Icmpv6FrameHeader {
                    src_mac: *src_mac,
                    dst_mac: *dst_mac,
                    src_ip: *src_ip,
                    dst_ip: *dst_ip,
                    icmp_type: Icmpv6Type::RouterAdvertisement,
                };
                encode_icmpv6_frame(
                    buf,
                    &hdr,
                    |icmp_hdr| icmp_hdr.set_ra_fields(RA_CUR_HOP_LIMIT, 0, RA_ROUTER_LIFETIME_SECS),
                    |payload| {
                        RouterAdvertisementBuilder::new(payload)?
                            .rdnss(dns_server.octets(), u32::from(RA_ROUTER_LIFETIME_SECS))
                            .build(0, 0, src_mac.bytes, *prefix, *prefix_len)
                    },
                )
            }
        }
    }

    /// Encodes the NDP reply into a standalone `Bytes` packet.
    pub(crate) fn to_packet(&self) -> Option<Bytes> {
        let mut buf = [0u8; IPV6_MIN_MTU];
        let len = self.encode(&mut buf)?;
        buf.get(..len).map(Bytes::copy_from_slice)
    }
}

struct Icmpv6FrameHeader {
    src_mac: MacAddr,
    dst_mac: MacAddr,
    src_ip: Ipv6Addr,
    dst_ip: Ipv6Addr,
    icmp_type: Icmpv6Type,
}

fn encode_icmpv6_frame(
    buf: &mut [u8],
    hdr: &Icmpv6FrameHeader,
    set_hdr: impl FnOnce(&mut Icmpv6Header),
    encode_payload: impl FnOnce(&mut [u8]) -> Option<usize>,
) -> Option<usize> {
    let initial_len = buf.len();
    let (eth, rest_buf) = EthernetFrame::mut_from_prefix(buf).ok()?;
    let eth_hdr_len = initial_len - rest_buf.len();
    eth.dst_addr = hdr.dst_mac;
    eth.src_addr = hdr.src_mac;
    eth.ethertype = ether_type::IPV6.into();

    let mut ipv6_builder = Ipv6Builder::new(rest_buf, IP_P_ICMPV6, hdr.src_ip, hdr.dst_ip)?;
    ipv6_builder.hop_limit(NDP_HOP_LIMIT);

    let ipv6_payload = ipv6_builder.payload_mut();
    let initial_ipv6_payload_len = ipv6_payload.len();

    let icmpv6_len = {
        let (icmpv6_hdr, icmpv6_payload) = Icmpv6Header::mut_from_prefix(ipv6_payload).ok()?;
        icmpv6_hdr.icmpv6_type = hdr.icmp_type as u8;
        icmpv6_hdr.icmpv6_code = 0;
        icmpv6_hdr.icmpv6_checksum = 0.into();
        icmpv6_hdr.rest = [0; 4];
        set_hdr(icmpv6_hdr);

        let body_len = encode_payload(icmpv6_payload)?;
        let icmpv6_hdr_len = initial_ipv6_payload_len - icmpv6_payload.len();
        icmpv6_hdr_len + body_len
    };

    let icmpv6_bytes = ipv6_payload.get(..icmpv6_len)?;
    let checksum = icmpv6_checksum(icmpv6_bytes, hdr.src_ip, hdr.dst_ip);

    let (icmpv6_hdr, _) = Icmpv6Header::mut_from_prefix(ipv6_payload).ok()?;
    icmpv6_hdr.icmpv6_checksum.set(checksum);

    ipv6_builder.payload_len(icmpv6_len);
    let ipv6_total_len = ipv6_builder.build()?;

    Some(eth_hdr_len + ipv6_total_len)
}

/// Evaluates an incoming ICMPv6 packet and determines if an NDP response is required.
pub(crate) fn handle_ndp_packet(
    config: &Config,
    guest_mac: MacAddr,
    ipv6_header: &Ipv6Header,
    icmpv6_header: &Icmpv6Header,
    icmpv6_payload: &[u8],
) -> Option<NdpReply> {
    if icmpv6_header.icmpv6_type == Icmpv6Type::NeighborSolicitation as u8 {
        let ns = NeighborSolicitation::parse(icmpv6_payload)?;
        let target_ip = Ipv6Addr::from(ns.target_addr);
        if target_ip != config.host_ipv6 && target_ip != GATEWAY_LINK_LOCAL_IPV6 {
            return None;
        }

        let source_ip = Ipv6Addr::from(ipv6_header.source_addr);
        let (dst_ip, dst_mac, flags) = if source_ip.is_unspecified() {
            (ALL_NODES_MULTICAST_V6, ALL_NODES_MAC, na_flags::ROUTER | na_flags::OVERRIDE)
        } else {
            (source_ip, guest_mac, na_flags::ROUTER | na_flags::SOLICITED | na_flags::OVERRIDE)
        };

        Some(NdpReply::NeighborAdvertisement {
            src_mac: config.gateway_mac,
            dst_mac,
            src_ip: target_ip,
            dst_ip,
            target_ip,
            target_mac: config.gateway_mac,
            flags,
        })
    } else if icmpv6_header.icmpv6_type == Icmpv6Type::RouterSolicitation as u8 {
        let source_ip = Ipv6Addr::from(ipv6_header.source_addr);
        let (dst_ip, dst_mac) = if source_ip.is_unspecified() {
            (ALL_NODES_MULTICAST_V6, ALL_NODES_MAC)
        } else {
            (source_ip, guest_mac)
        };
        Some(NdpReply::router_advertisement(config, dst_ip, dst_mac))
    } else {
        None
    }
}
